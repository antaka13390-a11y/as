    public static string Get(string languageCode, string key)
    {
        IReadOnlyDictionary<string, string> dict = string.Equals(languageCode, "en", StringComparison.OrdinalIgnoreCase)
            ? English
            : Arabic;

        if (dict.TryGetValue(key, out string? value))
        {
            return value;
        }

        return English.TryGetValue(key, out string? fallback) ? fallback : key;
    }
